"""Shell completion scripts for ir8tools.

The option table below describes every tool's command line. Keep it in sync
when a tool's argparse options change. Shell scripts are generated from it,
so supporting another shell only needs a new generator.
"""
from .tool_descriptions import all_tools

# Option argument kinds
FLAG = None  # takes no argument
FILE = "file"  # takes a file path
TEXT = "text"  # takes a free-form value (no file completion)

# Positional argument kinds
FILES = "files"  # complete file paths
NONE = "none"  # nothing useful to complete

HELP = ("h", "help", "Show this help message and exit", FLAG)
VERSION = ("v", "version", "Print version information", FLAG)

# tool name -> {"options": [(short, long, description, arg kind)], "args": kind}
# "args" may also be a list of choices for the first positional argument.
TOOLS = {
    "base58": {
        "options": [
            ("d", "decode", "Decode data", FLAG),
            ("i", "ignore-garbage", "When decoding, ignore non-alphabet characters", FLAG),
            ("w", "wrap", "Wrap encoded lines after COLS characters (0 disables)", TEXT),
            (None, "help", "Display help and exit", FLAG),
            (None, "version", "Output version information and exit", FLAG),
        ],
        "args": FILES,
    },
    "ipinfo": {"options": [HELP, VERSION], "args": NONE},
    "dnsinfo": {
        "options": [HELP, VERSION],
        "args": "dns-types",  # filled in lazily: dnsinfo imports dnspython
    },
    "dnswho": {"options": [HELP, VERSION], "args": NONE},
    "pwned": {"options": [HELP, VERSION], "args": NONE},
    "gittu": {"options": [HELP, VERSION], "args": NONE},
    "warpwg": {
        "options": [
            ("d", "dns", "Include DNS servers in the configuration", FLAG),
            ("o", "output", "Output file path (- for stdout)", FILE),
            ("q", "qr", "Print QR config to stdout", FLAG),
            HELP,
            VERSION,
        ],
        "args": NONE,
    },
    "srcf": {
        "options": [
            ("u", "url-only", "Show url only", FLAG),
            ("a", "full", "Show full details including mirror name", FLAG),
            HELP,
            VERSION,
        ],
        "args": NONE,
    },
    "echoargs": {"options": [], "args": FILES},
}

SHELLS = ["fish"]


def _fish_quote(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _fish_option(cmd, short, long, desc, kind, condition=None):
    parts = ["complete -c", cmd]
    if condition:
        parts += ["-n", _fish_quote(condition)]
    if short:
        parts += ["-s", short]
    if long:
        parts += ["-l", long]
    if kind == FILE:
        parts.append("-r -F")
    elif kind == TEXT:
        parts.append("-x")
    parts += ["-d", _fish_quote(desc)]
    return " ".join(parts)


def _resolve_args(args):
    if args == "dns-types":
        from .dnsinfo import types

        return ["ALL"] + [t.strip() for t in types]
    return args


def fish():
    lines = [
        "# fish completions for ir8tools (generated by `ir8t --completions fish`)",
        "",
    ]

    for name, _, _ in all_tools[1:]:
        spec = TOOLS[name]
        lines.append("# " + name)
        args = _resolve_args(spec["args"])
        if args != FILES:
            lines.append("complete -c {} -f".format(name))
        if isinstance(args, list):
            lines.append(
                "complete -c {} -n '__fish_is_nth_token 1' -a {}".format(
                    name, _fish_quote(" ".join(args))
                )
            )
        for short, long, desc, kind in spec["options"]:
            lines.append(_fish_option(name, short, long, desc, kind))
        lines.append("")

    # ir8t: complete its own options and tool names until a tool is given,
    # then hand off to that tool's completions.
    no_tool = "__fish_use_subcommand"
    lines += [
        "# ir8t",
        "complete -c ir8t -f",
        _fish_option("ir8t", "l", "list", "Show the list of tools", FLAG, no_tool),
        _fish_option("ir8t", "h", "help", "Show help for a tool, or this message", FLAG, no_tool),
        _fish_option("ir8t", "v", "version", "Print version information", FLAG, no_tool),
        _fish_option("ir8t", None, "completions", "Print shell completion script", TEXT, no_tool)
        + " -a " + _fish_quote(" ".join(SHELLS)),
    ]
    for name, desc, _ in all_tools[1:]:
        lines.append(
            "complete -c ir8t -n {} -a {} -d {}".format(
                no_tool, name, _fish_quote(desc)
            )
        )
    lines.append(
        "complete -c ir8t -n 'not {}' -x -a '(__fish_complete_subcommand)'".format(no_tool)
    )

    return "\n".join(lines) + "\n"


GENERATORS = {"fish": fish}


def get_script(shell):
    return GENERATORS[shell]()
